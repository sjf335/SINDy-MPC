"""Verify every nominal control-period measurement and export the manuscript benchmark."""
import argparse
from pathlib import Path

from profile_pelican_realtime import DEFAULT_OUT, KINDS, ORDER, ROOT, SEED, SOURCE, checksum, load, write_json
import numpy as np
import pandas as pd

LABELS = {'pd': 'PD', 'sindy_current': 'SINDy', 'linear_history': 'Linear history',
          'motor_sindy': 'Motor SINDy', 'sindy_history': 'History SINDy'}
BUDGET_S = 0.05


def verify_periods(folder, baseline=None):
    controls = pd.read_csv(folder/'control.csv', float_precision='round_trip')
    metrics = load(folder/'metrics.json')
    assert len(controls) == 400 and metrics['complete'] and metrics['control_calls'] == 400
    steps = controls.step.to_numpy()
    np.testing.assert_array_equal(steps, np.arange(0, 2000, 5))
    with np.load(folder/'trajectory.npz') as signals:
        # Tick k charges the current command, four earlier packs and five latest feedback updates.
        # At k=0 there are no earlier samples, and feedback_seconds[0] is the initialization sentinel.
        packing = signals['pack_seconds']
        feedback = signals['feedback_seconds']
        assert len(packing) == 2000 and len(feedback) == 2001 and feedback[0] == 0
        feedback_work = np.array([sum(feedback[k-4:k+1]) if k else 0 for k in steps])
        packing_work = np.array([sum(packing[k-4:k]) if k else 0 for k in steps])
        reconstructed = controls.command_compute_s + feedback_work + packing_work
        np.testing.assert_allclose(reconstructed, controls.full_control_period_s, atol=2e-14, rtol=1e-12)
        np.testing.assert_array_equal(reconstructed > BUDGET_S, controls.full_control_period_s > BUDGET_S)
        if baseline is not None:
            with np.load(baseline/'trajectory.npz') as original:
                for field in ('initial_history_states','initial_history_commands','reference'):
                    np.testing.assert_array_equal(signals[field], original[field])
                for field in ('command','physical'):
                    np.testing.assert_allclose(signals[field], original[field], atol=1e-7, rtol=1e-8)
    assert controls.success.dtype == bool and controls.fallback.dtype == bool
    assert int((~controls.success).sum()) == metrics['solver_failures']
    assert int(controls.fallback.sum()) == metrics['fallbacks']
    assert bool((controls.seconds >= 0).all()) and bool((controls.command_compute_s >= controls.seconds).all())
    np.testing.assert_allclose(controls.full_control_period_s.max(), metrics['full_control_period_max_s'])
    np.testing.assert_allclose((controls.full_control_period_s > BUDGET_S).mean(), metrics['full_control_over_period_fraction'])
    return controls, metrics


def summarize(ticks):
    serial = ticks.cohort.iat[0] == 'serial'
    is_mpc = ticks.controller.iat[0] != 'pd'
    result = dict(calls=len(ticks), solver_failures=int((~ticks.success).sum()) if is_mpc else None,
                  solver_failure_pct=100*(~ticks.success).mean() if is_mpc else None,
                  fallbacks=int(ticks.fallback.sum()), fallback_pct=100*ticks.fallback.mean())
    for label,column in [('solver','seconds'), ('period','full_control_period_s')]:
        values = ticks[column].to_numpy()*1000
        if label=='solver' and not is_mpc:
            continue
        result.update({label+'_mean_ms':values.mean(), label+'_p95_ms':np.quantile(values,.95),
                       label+'_p99_ms':np.quantile(values,.99), label+'_max_ms':values.max(),
                       label+'_misses':np.count_nonzero(values>50), label+'_miss_pct':100*np.mean(values>50)})
    result['peak_working_set_mib']=ticks.peak_working_set_mib.max() if serial else None
    return result


def make_table(summary, path):
    data=summary[summary.cohort=='serial'].set_index('controller')
    rows=[]
    for name in ORDER:
        row=data.loc[name]
        solve='-- & --' if name=='pd' else f'{row.solver_mean_ms:.1f} & {row.solver_max_ms:.1f}'
        name_tex=LABELS[name]
        rows.append(f'{name_tex} & {solve} & {row.period_mean_ms:.1f} & {row.period_p95_ms:.1f} & '
                    f'{row.period_max_ms:.1f} & {row.period_miss_pct:.2f} & {row.peak_working_set_mib:.0f} '+r'\\')
    tex=r'''% Generated by method/scripts/report_pelican_realtime.py
\begin{table}[!ht]
\centering
\caption{Computational Cost on the AMD Ryzen 9 7945HX}
\label{tab:realtime}
\footnotesize
\setlength{\tabcolsep}{2.4pt}
\begin{tabular}{@{}lrrrrrrr@{}}
\toprule
 & \multicolumn{2}{c}{Solve (ms)} & \multicolumn{3}{c}{Cycle (ms)} & Late & RAM \\
\cmidrule(lr){2-3}\cmidrule(lr){4-6}
Controller & Mean & Max & Mean & P95 & Max & (\%) & (MiB) \\
\midrule
'''+'\n'.join(rows)+r'''
\bottomrule
\end{tabular}
\par\smallskip
\parbox{\columnwidth}{\footnotesize Each row covers 1,200 control updates.
Late denotes cycles exceeding 50~ms. RAM is the largest process peak
working set across the three trials, including the Python runtime, solver
when applicable, simulator and in-memory logs.}
\end{table}
'''
    path.write_text(tex,encoding='utf-8')


def main(out, tables):
    frozen=load(SOURCE/'artifact_hashes.json')['files']
    index_path=SOURCE/'validate/tracking_per_run.csv'
    assert checksum(index_path)==load(SOURCE/'validate/COMPLETED.json')['tracking_sha256']
    index=pd.read_csv(index_path)
    assert len(index)==75 and not index.duplicated(['controller','trajectory','seed']).any()
    assert load(SOURCE/'config.json')['workers']==4
    design=load(out/'design.json')
    assert design['independent_workers']==1 and len(design['trials'])==15
    trials=[]
    storage=[]
    for case in index.itertuples(index=False):
        baseline=SOURCE/'validate/cases'/case.case_id
        for cohort in ('archived', 'serial') if case.seed==SEED else ('archived',):
            memory_mib = None
            if cohort=='archived':
                folder=baseline
                for key in ('metrics.json','trajectory.npz','control.csv'):
                    rel=(folder/key).relative_to(ROOT).as_posix()
                    assert checksum(folder/key)==frozen[rel]['sha256'], rel
            else:
                stem=f'{case.trajectory}_{case.seed}_{case.controller}'
                folder=out/'cases'/stem
                stamp=load(out/'memory'/f'{stem}.json')
                assert stamp['environment']==design['hardware']
                assert all(pool['num_threads']==1 for pool in stamp['threadpools'])
                for key,digest in stamp['hashes'].items():
                    assert checksum(folder/key)==digest, folder/key
                stages=stamp['memory']
                peak=[stages[key]['peak_working_set_bytes'] for key in ('before_construction','after_construction','before_archive')]
                assert peak==sorted(peak) and peak[0]>0
                memory_mib=peak[-1]/2**20
            ticks,m=verify_periods(folder, baseline if cohort=='serial' else None)
            assert (m['controller'],m['trajectory'],m['seed'])==(case.controller,case.trajectory,case.seed)
            ticks=ticks.assign(cohort=cohort,controller=case.controller,trajectory=case.trajectory,
                               seed=case.seed,peak_working_set_mib=memory_mib)
            trials.append(dict(cohort=cohort,controller=case.controller,trajectory=case.trajectory,seed=case.seed,**summarize(ticks)))
            storage.append(ticks)
    data=pd.concat(storage,ignore_index=True)
    rows=[]
    for (cohort,name),ticks in data.groupby(['cohort','controller']):
        assert len(ticks)==(1200 if cohort=='serial' else 6000)
        rows.append(dict(cohort=cohort,controller=name,**summarize(ticks)))
    summary=pd.DataFrame(rows)
    assert len(summary)==10 and len(data)==36000
    trial_data=pd.DataFrame(trials)
    trial_data.to_csv(out/'timing_by_trial.csv',index=False)
    summary.to_csv(out/'timing_summary.csv',index=False)
    if tables:
        make_table(summary,ROOT.parent/'latex/tables/computational_cost.tex')
    write_json(out/'verification.json',dict(status='PASS',archived_control_updates=30000,serial_control_updates=6000,
        memory_profiles=15,independently_reconstructed_control_updates=len(data),paired_trajectory_and_command_checks=15,
        summary_sha256=checksum(out/'timing_summary.csv'),report_script_sha256=checksum(Path(__file__))))
    print(summary[['cohort','controller','solver_mean_ms','solver_max_ms','period_mean_ms','period_p95_ms',
                   'period_max_ms','period_misses','period_miss_pct','peak_working_set_mib','fallbacks']].round(3).to_string(index=False))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out',type=Path,default=DEFAULT_OUT)
    parser.add_argument('--write-table',action='store_true')
    args=parser.parse_args()
    main(args.out.resolve(),args.write_table)
