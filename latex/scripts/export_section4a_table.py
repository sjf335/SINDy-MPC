"""Verify saved prediction/ablation results and export the Section IV-A table."""
from __future__ import annotations

import json

import numpy as np
import pandas as pd

from plot_section4a import E2, LATEX, MODELS, LABELS, digest, load_and_validate

OUT = LATEX / "tables"
STEM = "section4a_prediction_accuracy"
METRICS = ["position", "velocity", "attitude", "omega"]
TABLE_MODELS = [model for model in MODELS if model != "sindy_history"] + ["sindy_history"]


def main():
    # Recompute the existing ablation means from all 32 saved nominal trajectories.
    _, _, ablation, _, sources, previous = load_and_validate()
    window_path = E2 / "test/prediction_per_window.csv"
    sources[window_path] = digest(window_path)
    windows = pd.read_csv(window_path)
    flights = pd.read_csv(E2 / "test/prediction_per_flight.csv")
    summary = pd.read_csv(E2 / "test/prediction_summary.csv")
    rows = []
    max_delta = 0.0
    expected_origins = None
    for horizon in [0.5, 1.0]:
        for model in TABLE_MODELS:
            group = windows[(windows.model == model) & (windows.horizon_s == horizon)]
            assert len(group) == 2515 and group.flight_id.nunique() == 11
            origins = set(zip(group.flight_id, group.origin_index))
            assert len(origins) == len(group)
            if expected_origins is None:
                expected_origins = origins
            assert origins == expected_origins
            recorded = summary[(summary.model == model) & (summary.horizon_s == horizon)]
            assert len(recorded) == 1
            recorded = recorded.iloc[0]
            perflight = []
            for flight_id, subset in group.groupby("flight_id"):
                successful = subset[~subset.failed]
                assert len(successful) > 0
                values = np.array([
                    np.sqrt(np.mean(successful[f"{metric}_error"].to_numpy()**2))
                    for metric in METRICS
                ])
                saved = flights[(flights.model == model) & (flights.horizon_s == horizon)
                                & (flights.flight_id == flight_id)]
                assert len(saved) == 1
                saved = saved.iloc[0]
                np.testing.assert_allclose(values, saved[[f"{m}_rmse" for m in METRICS]].to_numpy(dtype=float),
                                           rtol=1e-11, atol=1e-13)
                assert int(subset.failed.sum()) == int(saved.failed_windows)
                perflight.append(values)
            means = np.mean(perflight, axis=0)
            stored = recorded[[f"{m}_rmse_mean" for m in METRICS]].to_numpy(dtype=float)
            np.testing.assert_allclose(means, stored, rtol=1e-11, atol=1e-13)
            max_delta = max(max_delta, float(np.max(abs(means-stored))))
            failures = int(group.failed.sum())
            assert failures == int(recorded.failed_windows)
            rows.append({"model": model, "horizon_s": horizon, "windows": len(group),
                         "failed_windows": failures,
                         **{f"{m}_rmse_mean": float(v) for m, v in zip(METRICS, means)}})
    result = pd.DataFrame(rows)
    OUT.mkdir(exist_ok=True)
    (OUT / "data").mkdir(exist_ok=True)
    csv_path = OUT / "data" / f"{STEM}.csv"
    result.to_csv(csv_path, index=False)

    lines = [
        "% Generated by scripts/export_section4a_table.py from saved test results.",
        r"\begin{table}[!htbp]",
        r"  \centering",
        r"  \caption{Endpoint Prediction Errors on Pelican Test Flights}",
        r"  \label{tab:prediction-accuracy}",
        r"  \footnotesize",
        r"  \setlength{\tabcolsep}{2.5pt}",
        r"  \renewcommand{\arraystretch}{1.08}",
        r"  \begin{tabular}{@{}lrrrrr@{}}",
        r"    \toprule",
        r"    Model & $\mathrm{RMSE}_p$ & $\mathrm{RMSE}_v$ & $\mathrm{RMSE}_R$ & $\mathrm{RMSE}_{\omega}$ & Failed \\",
        r"    & (m) & (m/s) & (rad) & (rad/s) & \\",
    ]
    minima = {}
    for horizon in [0.5, 1.0]:
        group = result[result.horizon_s == horizon]
        minima[horizon] = {m: float(group[f"{m}_rmse_mean"].min()) for m in METRICS}
        lines.extend([r"    \midrule", rf"    \multicolumn{{6}}{{c}}{{Prediction horizon: {horizon:g}~s}} \\", r"    \midrule"])
        for row in group.itertuples():
            label = ("SINDy (MD)"
                     if row.model == "motor_sindy" else LABELS[row.model])
            cells = [label]
            for metric in METRICS:
                value = getattr(row, f"{metric}_rmse_mean")
                cell = f"{value:.4f}"
                if value == minima[horizon][metric]:
                    cell = r"\textbf{" + cell + "}"
                cells.append(cell)
            cells.append(str(row.failed_windows))
            lines.append("    " + " & ".join(cells) + r" \\")
    lines.extend([
        r"    \bottomrule",
        r"  \end{tabular}",
        r"  \par\smallskip",
        r"  \parbox{\columnwidth}{\footnotesize",
        r"    Results use 2,515 common windows from 11 test flights.",
        r"    Each model's RMSE is computed on its completed windows within",
        r"    each flight, then averaged equally across flights.",
        r"    Subscripts $p$, $v$, $R$, and $\omega$ denote position,",
        r"    velocity, relative rotation angle, and body angular rate.",
        r"    The last column counts terminated windows out of 2,515.",
        r"    MD denotes motor dynamics.",
        r"    Bold denotes the lowest mean in each metric and horizon.}",
        r"\end{table}",
    ])
    table_path = OUT / f"{STEM}.tex"
    table_path.write_text("\n".join(lines)+"\n", encoding="utf-8")

    half = result[result.horizon_s == 0.5].set_index("model")
    reductions = {
        "velocity_vs_current_percent": 100*(1-half.loc["sindy_history", "velocity_rmse_mean"] / half.loc["sindy_current", "velocity_rmse_mean"]),
        "position_vs_current_percent": 100*(1-half.loc["sindy_history", "position_rmse_mean"] / half.loc["sindy_current", "position_rmse_mean"]),
        "velocity_vs_linear_percent": 100*(1-half.loc["sindy_history", "velocity_rmse_mean"] / half.loc["linear_history", "velocity_rmse_mean"]),
    }
    for path, value in sources.items():
        assert digest(path) == value, path
    report = {
        "status": "PASS", "prediction_table_rows": len(result),
        "model_display_order": TABLE_MODELS,
        "per_window_records_checked": 2515*len(result), "per_flight_metric_groups_checked": 11*len(result),
        "prediction_max_absolute_difference": max_delta,
        "prediction_aggregation": "Within-flight RMSE over each model's completed windows, then arithmetic mean over 11 flights.",
        "reductions_at_0p5s": {k: float(v) for k, v in reductions.items()},
        "ablation_trajectories_recomputed": previous["ablation_trajectories_recomputed"],
        "ablation_max_absolute_difference_m": previous["ablation_max_absolute_check_difference_m"],
        "ablation_summary": ablation.to_dict(orient="records"),
        "source_hashes_unchanged": True,
        "source_sha256": {str(p.relative_to(LATEX.parent)).replace("\\", "/"): h for p, h in sources.items()},
        "output_sha256": {p.name: digest(p) for p in [table_path, csv_path]},
    }
    (OUT / f"{STEM}_verification.json").write_text(json.dumps(report, indent=2)+"\n", encoding="utf-8")
    print(json.dumps({k: v for k, v in report.items() if k not in ["source_sha256", "output_sha256", "ablation_summary"]}, indent=2))


if __name__ == "__main__":
    main()
