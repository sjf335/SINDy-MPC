"""Export Table III from raw frozen validation trajectories and commands."""
import json

import numpy as np
import pandas as pd

from section4b_data import KINDS, LATEX, ORDER, digest, load_validation, verify_sources


def main():
    _, per_run, by_trajectory, overall, sources, report = load_validation()
    out = LATEX / "tables"
    out.mkdir(exist_ok=True)
    per_run.to_csv(out / "section4b_tracking_per_run.csv", index=False)
    by_trajectory.to_csv(out / "section4b_tracking_by_trajectory.csv", index=False)
    overall.to_csv(out / "section4b_tracking_metrics.csv", index=False)
    gains = []
    for kind in KINDS:
        h = per_run[(per_run.trajectory == kind) & (per_run.controller == "sindy_history")].set_index("seed")
        for baseline in ORDER[:-1]:
            b = per_run[(per_run.trajectory == kind) & (per_run.controller == baseline)].set_index("seed")
            gains.append(dict(trajectory=kind, baseline=baseline, n=5,
                              full_rmse_reduction_percent=100 * (1 - h.position_rmse_m.mean() / b.position_rmse_m.mean()),
                              late_rmse_reduction_percent=100 * (1 - h.late_rmse_m.mean() / b.late_rmse_m.mean()),
                              full_history_wins=int((h.position_rmse_m < b.position_rmse_m).sum()),
                              late_history_wins=int((h.late_rmse_m < b.late_rmse_m).sum())))
    pd.DataFrame(gains).to_csv(out / "section4b_history_comparisons.csv", index=False)

    keys = [f"{kind}_rmse_cm" for kind in KINDS] + ["late_rmse_cm", "command_variation_mean_cu2"]
    best = {key: overall[key].min() for key in keys}
    lines = [
        r"% Generated by scripts/export_section4b_table.py; five held-out states per trajectory.",
        r"\begin{table*}[!t]",
        r"  \centering",
        r"  \caption{Tracking Performance from Test Initial Conditions}",
        r"  \label{tab:tracking}",
        r"  \footnotesize",
        r"  \setlength{\tabcolsep}{6pt}",
        r"  \renewcommand{\arraystretch}{1.12}",
        r"  \begin{tabular}{@{}lccccc@{}}",
        r"    \toprule",
        r"    & \multicolumn{3}{c}{Position RMSE, 0--20 s (cm)} & RMSE, 10--20 s & Command variation \\",
        r"    \cmidrule(lr){2-4}",
        r"    Controller & Circle & Figure eight & Helix & (cm) & ($\mathrm{cu}^2$) \\",
        r"    \midrule",
    ]
    for row in overall.to_dict("records"):
        label = ("SINDy-MPC (MD)"
                 if row["controller"] == "motor_sindy" else row["label"])
        cells = [label]
        for key in keys:
            val = row[key]
            number = f"{val:.2f}"
            if key in keys[:3]:
                std_key = key.replace("_rmse_cm", "_rmse_std_cm")
                number += rf"\pm{row[std_key]:.2f}"
            if np.isclose(val, best[key], rtol=0, atol=1e-10):
                number = rf"\boldsymbol{{{number}}}"
            cells.append("$" + number + "$")
        lines.append("    " + " & ".join(cells) + r" \\")
    lines += [
        r"    \bottomrule",
        r"  \end{tabular}",
        r"  \par\smallskip",
        r"  \parbox{\textwidth}{\footnotesize",
        r"    Results for each trajectory are mean $\pm$ sample standard deviation",
        r"    over five paired initial conditions. The final two columns are",
        r"    equally weighted means over all 15 trials per controller.",
        r"    Command variation sums squared command increments, including the",
        r"    first increment after initialization; $\mathrm{cu}$ denotes command units.",
        r"    MD denotes motor dynamics.",
        r"    Bold indicates the lowest mean in each column.}",
        r"\end{table*}",
    ]
    table = out / "section4b_tracking_metrics.tex"
    table.write_text("\n".join(lines) + "\n", encoding="utf-8")
    verify_sources(sources, report)
    report["outputs_sha256"] = {p.name: digest(p) for p in
                               sorted(out.glob("section4b_*.csv")) + [table]}
    (out / "section4b_tracking_verification.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(overall.to_string(index=False))
    print("PASS: 300 position metrics and 75 command-variation metrics recomputed.")


if __name__ == "__main__":
    main()
